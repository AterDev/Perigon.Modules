using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Perigon.OpenApi.SourceGeneration;

/// <summary>Generates AOT-safe enum display metadata for the API OpenAPI transformer.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class EnumOpenApiMetadataGen : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor UnsupportedEnumValue = new(
        "PAOPENAPI001", "Enum value cannot be represented by OpenAPI metadata",
        "Enum '{0}.{1}' has a value that cannot be represented by the Int32 x-enumData metadata",
        "OpenAPI", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(context.CompilationProvider, static (spc, compilation) =>
        {
            if (!string.Equals(compilation.AssemblyName, "ApiService", StringComparison.Ordinal)) return;

            var enums = new List<EnumInfo>();
            foreach (var reference in compilation.SourceModule.ReferencedAssemblySymbols)
            {
                if (reference.Name is not ("Entity" or "Perigon.AspNetCore" or "Share")) continue;
                CollectEnums(reference.GlobalNamespace, enums, spc);
            }

            enums.Sort(static (left, right) => StringComparer.Ordinal.Compare(left.TypeName, right.TypeName));
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using System;");
            source.AppendLine("using System.Collections.Generic;");
            source.AppendLine("using Perigon.AspNetCore.Utils;");
            source.AppendLine("namespace ApiService.OpenApi;");
            source.AppendLine("internal static class GeneratedEnumOpenApiMetadata");
            source.AppendLine("{");
            source.AppendLine("    public static IReadOnlyDictionary<Type, IReadOnlyList<EnumDictionary>> Values { get; } = new Dictionary<Type, IReadOnlyList<EnumDictionary>>");
            source.AppendLine("    {");
            foreach (var item in enums)
            {
                source.Append("        [typeof(").Append(item.TypeName).AppendLine(")] = new List<EnumDictionary>");
                source.AppendLine("        {");
                foreach (var member in item.Members)
                {
                    source.Append("            new EnumDictionary { Name = ")
                        .Append(FormatLiteral(member.Name))
                        .Append(", Description = ")
                        .Append(FormatLiteral(member.Description))
                        .Append(", Value = ")
                        .Append(member.Value)
                        .AppendLine(" },");
                }
                source.AppendLine("        },");
            }
            source.AppendLine("    };");
            source.AppendLine("}");
            spc.AddSource("GeneratedEnumOpenApiMetadata.g.cs", source.ToString());
        });
    }

    private static void CollectEnums(INamespaceSymbol space, List<EnumInfo> result, SourceProductionContext context)
    {
        foreach (var type in space.GetTypeMembers())
        {
            if (type.TypeKind != TypeKind.Enum || type.DeclaredAccessibility != Accessibility.Public) continue;

            var members = type.GetMembers().OfType<IFieldSymbol>()
                .Where(field => field.IsConst && field.Name != "value__")
                .Select(field => CreateMember(field, type, context))
                .Where(member => member is not null)
                .Select(member => member!)
                .ToImmutableArray();
            result.Add(new EnumInfo(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), members));
        }

        foreach (var child in space.GetNamespaceMembers()) CollectEnums(child, result, context);
    }

    private static string GetDescription(IFieldSymbol field)
    {
        var attribute = field.GetAttributes().FirstOrDefault(item =>
            item.AttributeClass?.ToDisplayString() == "System.ComponentModel.DescriptionAttribute");
        return attribute?.ConstructorArguments.FirstOrDefault().Value?.ToString() ?? field.Name;
    }

    private static EnumMember? CreateMember(IFieldSymbol field, INamedTypeSymbol type, SourceProductionContext context)
    {
        if (!TryFormatValue(field.ConstantValue, out string value))
        {
            context.ReportDiagnostic(Diagnostic.Create(UnsupportedEnumValue, field.Locations.FirstOrDefault(), type.Name, field.Name));
            return null;
        }

        return new EnumMember(field.Name, value, GetDescription(field));
    }

    private static bool TryFormatValue(object? rawValue, out string value)
    {
        long numericValue;
        switch (rawValue)
        {
            case sbyte number: numericValue = number; break;
            case byte number: numericValue = number; break;
            case short number: numericValue = number; break;
            case ushort number: numericValue = number; break;
            case int number: numericValue = number; break;
            case uint number when number <= int.MaxValue: numericValue = number; break;
            case long number when number is >= int.MinValue and <= int.MaxValue: numericValue = number; break;
            case ulong number when number <= (ulong)int.MaxValue: numericValue = (long)number; break;
            default:
                value = string.Empty;
                return false;
        }

        value = numericValue.ToString(CultureInfo.InvariantCulture);
        return true;
    }

    // Keep generated source valid for descriptions containing quotes, slashes, line breaks,
    // control characters, or Unicode line separators. This deliberately emits a regular
    // C# string literal instead of copying the attribute text into generated source.
    private static string FormatLiteral(string value)
    {
        StringBuilder builder = new(value.Length + 2);
        builder.Append('"');
        foreach (char character in value)
        {
            switch (character)
            {
                case '\\': builder.Append("\\\\"); break;
                case '"': builder.Append("\\\""); break;
                case '\n': builder.Append("\\n"); break;
                case '\r': builder.Append("\\r"); break;
                case '\t': builder.Append("\\t"); break;
                case '\b': builder.Append("\\b"); break;
                case '\f': builder.Append("\\f"); break;
                case '\a': builder.Append("\\a"); break;
                case '\v': builder.Append("\\v"); break;
                default:
                    if (char.IsControl(character) || character is '\u2028' or '\u2029')
                    {
                        builder.Append("\\u").Append(((int)character).ToString("X4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(character);
                    }
                    break;
            }
        }

        return builder.Append('"').ToString();
    }

    private sealed class EnumInfo
    {
        public EnumInfo(string typeName, ImmutableArray<EnumMember> members) { TypeName = typeName; Members = members; }
        public string TypeName { get; }
        public ImmutableArray<EnumMember> Members { get; }
    }

    private sealed class EnumMember
    {
        public EnumMember(string name, string value, string description) { Name = name; Value = value; Description = description; }
        public string Name { get; }
        public string Value { get; }
        public string Description { get; }
    }
}
